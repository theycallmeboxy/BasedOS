#!/usr/bin/env python3
"""Make boot-ui's font header from a PSF2 console font.

  mkfont.py <font.psf[.gz]> <out.h>

Takes printable ASCII (0x20-0x7e) and the full block U+2588 (the cursor) through the font's
Unicode table, and writes them as C arrays, one bit per pixel, rows top to bottom, most
significant bit leftmost. BasedOS uses Terminus Font's bold 16x32
(console-setup's Uni2-TerminusBold32x16.psf.gz); see OFL-Terminus.txt for its licence.
"""
import gzip
import struct
import sys

WANT = list(range(0x20, 0x7F)) + [0x2588]


def main():
    src, out = sys.argv[1], sys.argv[2]
    data = (gzip.open if src.endswith(".gz") else open)(src, "rb").read()
    magic, version, hsize, flags, length, charsize, height, width = struct.unpack_from("<8I", data, 0)
    if magic != 0x864AB572:
        sys.exit("not a PSF2 font")
    glyphs = data[hsize:hsize + length * charsize]
    # Unicode table: per glyph, UTF-8 code points, then 0xff; 0xfe starts multi-char sequences.
    table, pos, index = {}, hsize + length * charsize, 0
    while index < length and pos < len(data):
        end = data.index(b"\xff", pos)
        entry = data[pos:end].split(b"\xfe")[0]
        for ch in entry.decode("utf-8", "ignore"):
            table.setdefault(ord(ch), index)
        pos, index = end + 1, index + 1
    if not (flags & 1):
        table = {c: c for c in WANT}
    missing = [hex(c) for c in WANT if c not in table]
    if missing:
        sys.exit(f"font lacks {missing}")
    stride = (width + 7) // 8
    with open(out, "w", newline="\n") as f:
        f.write("/* Generated by tools/boot-ui/mkfont.py from Terminus Font (bold 16x32), Copyright (c)\n"
                " * 2010 Dimitar Toshkov Zhekov, under the SIL Open Font License 1.1: see OFL-Terminus.txt.\n"
                " * Printable ASCII 0x20-0x7e, then U+2588 (full block). */\n")
        f.write(f"#define FONT_W {width}\n#define FONT_H {height}\n#define FONT_STRIDE {stride}\n")
        f.write(f"#define FONT_BLOCK {len(WANT) - 1}\n")
        f.write(f"static const unsigned char font_glyphs[{len(WANT)}][{charsize}] = {{\n")
        for c in WANT:
            g = glyphs[table[c] * charsize:(table[c] + 1) * charsize]
            f.write("\t{" + ",".join(f"0x{b:02x}" for b in g) + "},\n")
        f.write("};\n")
    print(f"{out}: {len(WANT)} glyphs, {width}x{height}")


if __name__ == "__main__":
    main()
